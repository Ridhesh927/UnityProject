
using UnityEngine;
using UnityEditor;

public class GenerateArenaDecorations : EditorWindow
{
    private const string GeneratedName = "ArenaDecorations_Auto";
    private const string TileFolder = "Assets/Sprites/Tiles";

    [MenuItem("Tools/ON THE LIVE/Generate Arena Decorations")]
    public static void Generate()
    {
        GameObject arena = GameObject.Find("ArenaFloor");

        if (arena == null)
        {
            Debug.LogError("Could not find ArenaFloor in the scene.");
            return;
        }

        // Find the existing floor tiles to calculate the arena bounds.
        SpriteRenderer[] renderers =
            arena.GetComponentsInChildren<SpriteRenderer>(true);

        Bounds bounds = new Bounds();
        bool foundFloor = false;

        foreach (SpriteRenderer sr in renderers)
        {
            if (!sr.gameObject.name.StartsWith("FloorTile"))
                continue;

            if (!foundFloor)
            {
                bounds = sr.bounds;
                foundFloor = true;
            }
            else
            {
                bounds.Encapsulate(sr.bounds);
            }
        }

        if (!foundFloor)
        {
            Debug.LogError(
                "No SpriteRenderers named FloorTile... found under ArenaFloor."
            );
            return;
        }

        // Remove only the decorations generated by this tool.
        GameObject old = GameObject.Find(GeneratedName);

        if (old != null)
            Undo.DestroyObjectImmediate(old);

        GameObject root = new GameObject(GeneratedName);
        Undo.RegisterCreatedObjectUndo(root, "Generate Arena Decorations");

        float insetX = bounds.extents.x * 0.72f;
        float insetY = bounds.extents.y * 0.72f;

        // Four edge accents, leaving the central combat area open.
        PlaceTile(root.transform, "scifiTile_04",
            new Vector3(bounds.center.x - insetX,
                        bounds.center.y + insetY, 0), 0);

        PlaceTile(root.transform, "scifiTile_04",
            new Vector3(bounds.center.x + insetX,
                        bounds.center.y + insetY, 0), 180);

        PlaceTile(root.transform, "scifiTile_08",
            new Vector3(bounds.center.x - insetX,
                        bounds.center.y - insetY, 0), 180);

        PlaceTile(root.transform, "scifiTile_08",
            new Vector3(bounds.center.x + insetX,
                        bounds.center.y - insetY, 0), 0);

        // Side accents.
        PlaceTile(root.transform, "scifiTile_03",
            new Vector3(bounds.center.x - insetX,
                        bounds.center.y, 0), 90);

        PlaceTile(root.transform, "scifiTile_03",
            new Vector3(bounds.center.x + insetX,
                        bounds.center.y, 0), -90);

        Debug.Log("Arena decorations generated. Inspect the Scene view.");
    }

    private static void PlaceTile(
        Transform parent, string tileName, Vector3 position, float rotation)
    {
        Sprite sprite = FindSprite(tileName);

        if (sprite == null)
        {
            Debug.LogWarning("Could not find sprite: " + tileName);
            return;
        }

        GameObject obj = new GameObject(tileName);
        obj.transform.SetParent(parent);
        obj.transform.position = position;
        obj.transform.rotation = Quaternion.Euler(0, 0, rotation);

        SpriteRenderer sr = obj.AddComponent<SpriteRenderer>();
        sr.sprite = sprite;
        sr.sortingOrder = 1;
    }

    private static Sprite FindSprite(string spriteName)
    {
        string[] guids = AssetDatabase.FindAssets(
            spriteName, new[] { TileFolder });

        foreach (string guid in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);

            foreach (Object asset in AssetDatabase.LoadAllAssetsAtPath(path))
            {
                if (asset is Sprite sprite &&
                    (sprite.name == spriteName ||
                     sprite.name.StartsWith(spriteName + "_")))
                {
                    return sprite;
                }
            }
        }

        return null;
    }
}
